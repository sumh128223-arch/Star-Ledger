def auto_categorize(
    merchant: str,
    product: str,
    extra_rules: dict | None = None,
    trans_type: str = "",          # ★ 新增参数：交易类型（来自账单"交易类型"列）
) -> str:
    """
    extra_rules: 从数据库 category_rules 表查出来的 {分类名: [关键词,...]}，
    会和默认规则合并，且优先匹配 extra_rules（用户自定义规则优先级更高）。

    trans_type: 微信账单"交易类型"字段的原始值，例如：
        "商户消费" / "扫二维码付款" / "微信红包" / "转账" / "信用卡还款" 等。
        加进搜索文本里可以大幅提升识别率（尤其是转账、红包这类
        merchant/product 里没有有效信息的交易）。
    """
    # ★ 把 trans_type 也拼进搜索文本
    text = f"{merchant or ''} {product or ''} {trans_type or ''}"

    # 1. 先匹配用户自定义规则（优先级最高）
    if extra_rules:
        for category, keywords in extra_rules.items():
            if any(kw in text for kw in keywords):
                return category

    # 2. 再匹配默认规则
    for category, keywords in DEFAULT_RULES.items():
        if any(kw in text for kw in keywords):
            return category

    # 3. 关键词全部匹配失败时，用 trans_type 兜底（商户消费 → 购物 等）
    if trans_type and trans_type in _TRANS_TYPE_FALLBACK:
        return _TRANS_TYPE_FALLBACK[trans_type]

    return "未分类"
